/* =========================================================================
   COMPLETE REMAINING AUDIO FILES — Neural TTS (Edge / Alice style)
   Generates all remaining MP3s that weren't completed due to API quota.
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';
import { RAW_QUESTIONS } from '../src/mathData.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 45);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function saveMap(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const content = fs.readFileSync(MAP_FILE, 'utf8');
      const match = content.match(/export const audioMap = ({[\s\S]*?});/);
      if (match) map = JSON.parse(match[1]);
    } catch (e) {}
  }

  const seen = new Set();
  const phrases = [];

  for (const p of ALL_PHRASES) {
    if (!p.text || seen.has(p.text)) continue;
    seen.add(p.text);
    phrases.push(p);
  }

  for (const q of RAW_QUESTIONS) {
    if (q.prompt && !seen.has(q.prompt)) {
      seen.add(q.prompt);
      phrases.push({ text: q.prompt, style: 'question', aliasOf: q.spokenPrompt });
    }
    if (q.hint && !seen.has(q.hint)) {
      seen.add(q.hint);
      phrases.push({ text: q.hint, style: 'thinking', aliasOf: q.spokenHint });
    }
  }

  console.log(`Checking ${phrases.length} phrases for missing audio files...`);

  const tts = new MsEdgeTTS();
  await tts.setMetadata('en-US-AvaNeural', OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);

  let generated = 0, existing = 0;

  for (const [i, p] of phrases.entries()) {
    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    if (fs.existsSync(filePath) && fs.statSync(filePath).size > 0) {
      map[p.text] = publicPath;
      if (p.aliasOf) map[p.aliasOf] = publicPath;
      existing++;
      continue;
    }

    process.stdout.write(`[${i + 1}/${phrases.length}] Generating: ${p.text.slice(0, 45)}… `);

    try {
      const { audioStream } = tts._rawSSMLRequest(tts._SSMLTemplate(p.text));
      await new Promise((resolve, reject) => {
        const fileStream = fs.createWriteStream(filePath);
        audioStream.pipe(fileStream);
        fileStream.on('finish', resolve);
        fileStream.on('error', reject);
        audioStream.on('error', reject);
      });

      map[p.text] = publicPath;
      if (p.aliasOf) map[p.aliasOf] = publicPath;
      generated++;
      console.log('✔');
    } catch (err) {
      console.log(`✖ ${err.message}`);
    }

    if (generated > 0 && generated % 20 === 0) {
      saveMap(map);
    }
    await sleep(80);
  }

  saveMap(map);
  try { tts.close(); } catch (e) {}
  console.log(`Done! Newly generated: ${generated}, already existing: ${existing}. Total mapped: ${Object.keys(map).length}`);
}

main();

