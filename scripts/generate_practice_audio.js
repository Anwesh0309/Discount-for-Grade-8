/* =========================================================================
   GENERATE PRACTICE AUDIO — ElevenLabs Alice (Xb7hH8MSUJpSbSDYk0k2)
   Generates all 100 Practice Questions and 100 Hints for the 10 Worlds
   with proper English pronunciation (expanded numbers, percentages, dollars).
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts';
import { RAW_QUESTIONS } from '../src/mathData.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';
const API_KEY = 'sk_211353733c92fb81acf51695384060a57e6a9953a917382e';

const STYLE_SETTINGS = {
  question: { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  thinking: { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true }
};

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 40);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function saveMap(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_practice_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function fetchWithRetry(url, options, maxRetries = 2) {
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    const res = await fetch(url, options);
    if (res.status === 429) {
      console.log(`[Rate limit 429, waiting ${attempt * 1500}ms...]`);
      await sleep(attempt * 1500);
      continue;
    }
    return res;
  }
  return fetch(url, options);
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const content = fs.readFileSync(MAP_FILE, 'utf8');
      const match = content.match(/export const audioMap = ({[\s\S]*?});/);
      if (match) map = JSON.parse(match[1]);
    } catch (e) {}
  }

  const items = [];
  for (const q of RAW_QUESTIONS) {
    const spokenP = q.spokenPrompt || q.prompt;
    const spokenH = q.spokenHint || q.hint;
    items.push({
      type: 'prompt',
      world: q.worldIndex + 1,
      qNum: q.qIndex + 1,
      text: spokenP,
      displayText: q.prompt,
      style: 'question'
    });
    items.push({
      type: 'hint',
      world: q.worldIndex + 1,
      qNum: q.qIndex + 1,
      text: spokenH,
      displayText: q.hint,
      style: 'thinking'
    });
  }

  console.log(`Total Practice items to process: ${items.length} (100 prompts + 100 hints across 10 worlds)`);

  let elevenCount = 0;
  let fallbackCount = 0;
  let skipped = 0;
  let elevenQuotaHit = false;

  const edgeTTS = new MsEdgeTTS();
  await edgeTTS.setMetadata('en-US-AvaNeural', OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);

  for (const [idx, item] of items.entries()) {
    const hash = crypto.createHash('md5').update(item.text).digest('hex').slice(0, 6);
    const fileName = `audio_w${item.world}q${item.qNum}_${item.type}_${slugify(item.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    // If already generated and valid, record mapping and continue
    if (fs.existsSync(filePath) && fs.statSync(filePath).size > 2000) {
      map[item.text] = publicPath;
      if (item.displayText) map[item.displayText] = publicPath;
      skipped++;
      continue;
    }

    process.stdout.write(`[${idx + 1}/${items.length}] W${item.world}Q${item.qNum} (${item.type}): "${item.text.slice(0, 35)}…" `);

    let generatedWithEleven = false;

    if (!elevenQuotaHit) {
      try {
        const settings = STYLE_SETTINGS[item.style];
        const res = await fetchWithRetry(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
          method: 'POST',
          headers: {
            'xi-api-key': API_KEY,
            'Content-Type': 'application/json',
            Accept: 'audio/mpeg'
          },
          body: JSON.stringify({
            text: item.text,
            model_id: MODEL_ID,
            voice_settings: settings
          })
        });

        if (res.ok) {
          const buffer = Buffer.from(await res.arrayBuffer());
          fs.writeFileSync(filePath, buffer);
          map[item.text] = publicPath;
          if (item.displayText) map[item.displayText] = publicPath;
          elevenCount++;
          generatedWithEleven = true;
          console.log(`✔ [ElevenLabs Alice ${buffer.length} bytes]`);
        } else {
          const errText = await res.text();
          if (res.status === 401 || res.status === 402 || errText.includes('quota')) {
            console.log(`\n⚠ ElevenLabs quota reached (${res.status}): ${errText.slice(0, 100)}`);
            console.log('Switching to high-quality neural voice for remaining items to ensure zero missing files...');
            elevenQuotaHit = true;
          } else {
            console.log(`✖ ElevenLabs ${res.status}: ${errText.slice(0, 80)}`);
          }
        }
      } catch (err) {
        console.log(`✖ ElevenLabs error: ${err.message}`);
      }
    }

    if (!generatedWithEleven) {
      // Fallback: Generate high quality neural audio
      try {
        const { audioStream } = edgeTTS._rawSSMLRequest(edgeTTS._SSMLTemplate(item.text));
        await new Promise((resolve, reject) => {
          const fileStream = fs.createWriteStream(filePath);
          audioStream.pipe(fileStream);
          fileStream.on('finish', resolve);
          fileStream.on('error', reject);
          audioStream.on('error', reject);
        });

        map[item.text] = publicPath;
        if (item.displayText) map[item.displayText] = publicPath;
        fallbackCount++;
        console.log(`✔ [Neural TTS ${fs.statSync(filePath).size} bytes]`);
      } catch (fallbackErr) {
        console.error(`✖ Fallback error: ${fallbackErr.message}`);
      }
    }

    // Save map periodically every 10 items
    if ((elevenCount + fallbackCount) % 10 === 0) {
      saveMap(map);
    }

    await sleep(250);
  }

  saveMap(map);
  console.log(`\n======================================================`);
  console.log(`Practice Audio Generation Completed:`);
  console.log(`- ElevenLabs Alice: ${elevenCount}`);
  console.log(`- Neural TTS Fallback: ${fallbackCount}`);
  console.log(`- Reused Existing: ${skipped}`);
  console.log(`- Total audioMap entries: ${Object.keys(map).length}`);
  console.log(`======================================================\n`);
}

main().catch(console.error);

