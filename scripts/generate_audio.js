/* =========================================================================
   OFFLINE AUDIO GENERATION — ElevenLabs "Alice"
   Usage:  node scripts/generate_audio.js           (skips files that exist)
           node scripts/generate_audio.js --force   (re-generate everything)
   • Reads phrases from src/utils/lessonScript.js
   • Generates MP3s with ElevenLabs voice Alice (Xb7hH8MSUJpSbSDYk0k2)
   • Saves MP3s to public/assets/audio/ and maintains src/utils/audioMap.js
   • Safe retry on 429 rate limits + periodic audioMap writes
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';
import { RAW_QUESTIONS } from '../src/mathData.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';
const FALLBACK_API_KEY = 'sk_28edc0c9233ebad1d748b68b5dbffa42484f9c30cf11459c';

const STYLE_SETTINGS = {
  celebration:   { stability: 0.12, similarity_boost: 0.45, style: 0.75, use_speaker_boost: true },
  encouragement: { stability: 0.16, similarity_boost: 0.50, style: 0.65, use_speaker_boost: true },
  question:      { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  emphasis:      { stability: 0.16, similarity_boost: 0.50, style: 0.60, use_speaker_boost: true },
  thinking:      { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true },
  statement:     { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true },
  instruction:   { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true }
};

function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  for (const f of ['.env.local', '.env', path.join('..', '.env.local')]) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*"?([^"\r\n]+)"?/m);
    if (m) return m[1].trim();
  }
  return FALLBACK_API_KEY;
}

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 45);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function saveMap(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function fetchWithRetry(url, options, maxRetries = 3) {
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    const res = await fetch(url, options);
    if (res.status === 429) {
      const waitTime = attempt * 2000;
      console.log(`[Rate limit 429, waiting ${waitTime}ms (retry ${attempt}/${maxRetries})]`);
      await sleep(waitTime);
      continue;
    }
    return res;
  }
  return fetch(url, options);
}

async function main() {
  const force = process.argv.includes('--force');
  const apiKey = readEnvKey();
  if (!apiKey) {
    console.error('✖ ElevenLabs API key not found.');
    process.exit(1);
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Build phrase list from ALL_PHRASES and RAW_QUESTIONS
  const seen = new Set();
  const phrases = [];

  for (const p of ALL_PHRASES) {
    if (!p.text || seen.has(p.text)) continue;
    seen.add(p.text);
    phrases.push(p);
  }

  // Also ensure prompts and hints from RAW_QUESTIONS are covered
  for (const q of RAW_QUESTIONS) {
    if (q.prompt && !seen.has(q.prompt)) {
      seen.add(q.prompt);
      phrases.push({ text: q.prompt, style: 'question', aliasOf: q.spokenPrompt });
    }
    if (q.hint && !seen.has(q.hint)) {
      seen.add(q.hint);
      phrases.push({ text: q.hint, style: 'thinking', aliasOf: q.spokenHint });
    }
  }

  console.log(`Total unique narration phrases to process: ${phrases.length}`);

  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const content = fs.readFileSync(MAP_FILE, 'utf8');
      const match = content.match(/export const audioMap = ({[\s\S]*?});/);
      if (match) {
        map = JSON.parse(match[1]);
      }
    } catch (e) {}
  }

  let made = 0, skipped = 0, failed = 0;

  for (const [i, p] of phrases.entries()) {
    // If it's an alias to an existing spoken text, link it directly
    if (p.aliasOf && map[p.aliasOf]) {
      map[p.text] = map[p.aliasOf];
      skipped++;
      continue;
    }

    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    if (!force && fs.existsSync(filePath) && fs.statSync(filePath).size > 0) {
      map[p.text] = publicPath;
      if (p.aliasOf) map[p.aliasOf] = publicPath;
      skipped++;
      continue;
    }

    const s = STYLE_SETTINGS[p.style] || STYLE_SETTINGS.statement;
    process.stdout.write(`[${i + 1}/${phrases.length}] (${p.style}) ${p.text.slice(0, 50)}… `);

    try {
      const res = await fetchWithRetry(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
        method: 'POST',
        headers: {
          'xi-api-key': apiKey,
          'Content-Type': 'application/json',
          Accept: 'audio/mpeg'
        },
        body: JSON.stringify({
          text: p.text,
          model_id: MODEL_ID,
          voice_settings: s
        })
      });

      if (!res.ok) {
        throw new Error(`${res.status} ${await res.text()}`);
      }

      const buffer = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(filePath, buffer);
      map[p.text] = publicPath;
      if (p.aliasOf) map[p.aliasOf] = publicPath;
      made++;
      console.log('✔');
    } catch (e) {
      failed++;
      console.log(`✖ ${e.message.slice(0, 160)}`);
    }

    // Save periodically every 15 generations
    if (made > 0 && made % 15 === 0) {
      saveMap(map);
    }

    await sleep(350);
  }

  saveMap(map);
  console.log(`\nComplete! Generated: ${made}, Reused: ${skipped}, Failed: ${failed}. audioMap.js updated.`);
}

main();
